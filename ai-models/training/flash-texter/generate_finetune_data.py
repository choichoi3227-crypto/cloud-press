def fill_slots(template: str, slots: dict[str, list[str]], rng: random.Random) -> str:
    """{slot_name} 형태의 자리표시자를 무작위로 채운다."""
    result = template
    for slot_name, options in slots.items():
        if f"{{{slot_name}}}" in result:
            result = result.replace(f"{{{slot_name}}}", rng.choice(options))
    return result


def to_chatml(user_msg: str, assistant_msg: str, system_prompt: str) -> str:
    """Qwen ChatML 형식으로 변환 (단일 턴)."""
    return (
        f"<|im_start|>system\n{system_prompt}<|im_end|>\n"
        f"<|im_start|>user\n{user_msg}<|im_end|>\n"
        f"<|im_start|>assistant\n{assistant_msg}<|im_end|>"
    )


def to_chatml_multiturn(turns: list[tuple[str, str]], system_prompt: str) -> str:
    """여러 (user, assistant) 쌍을 하나의 ChatML 시퀀스로 직렬화한다."""
    parts = [f"<|im_start|>system\n{system_prompt}<|im_end|>"]
    for user_msg, assistant_msg in turns:
        parts.append(f"<|im_start|>user\n{user_msg}<|im_end|>")
        parts.append(f"<|im_start|>assistant\n{assistant_msg}<|im_end|>")
    return "\n".join(parts)


