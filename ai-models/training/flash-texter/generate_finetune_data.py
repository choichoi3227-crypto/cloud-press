def generate(out_path: str, repeat_per_template: int, seed: int = 42, per_category_cap: int = 1000) -> None:
    """
    각 카테고리에서 만들 수 있는 모든 (입력 템플릿 x 응답 템플릿 x 슬롯 조합)을
    실제로 전부 열거한 뒤, 그중에서 필요한 만큼 중복 없이 뽑는다.
    repeat_per_template로 요청한 수가 실제 조합 가능 수보다 많으면, 중복을 채우는
    대신 가능한 최대치까지만 생성하고 그 사실을 명시적으로 알린다.
    """
    rng = random.Random(seed)
    rows = []

    for category, spec in CATEGORIES.items():
        inputs = spec["inputs"]
        responses = spec["responses"]
        slots = spec.get("slots", {})

        slot_names = list(slots.keys())
        if slot_names:
            slot_value_lists = [slots[name] for name in slot_names]
            slot_combos = list(itertools.product(*slot_value_lists))
        else:
            slot_combos = [()]

        all_combos = list(itertools.product(inputs, responses, slot_combos))
        rng.shuffle(all_combos)
        available = len(all_combos)

        # explain_concept처럼 슬롯 조합이 매우 큰 카테고리(16,128개)가 전체 데이터셋을
        # 지배하면, 다른 카테고리(예: apology_response 8개)는 학습에 사실상 반영되지
        # 않는 극단적 불균형이 생긴다. per_category_cap으로 카테고리 하나가 가져갈 수
        # 있는 최대 행 수를 제한해 균형을 맞춘다 (repeat_per_template=0이어도 이 cap은
        # 적용된다 — "전량 사용"이 "가장 큰 카테고리가 전체를 삼킨다"는 뜻이 되지 않도록).
        requested = repeat_per_template if repeat_per_template > 0 else available
        if per_category_cap > 0:
            requested = min(requested, per_category_cap)
        take = min(requested, available)
        if repeat_per_template > 0 and repeat_per_template > available:
            print(
                f"[{category}] 요청한 {repeat_per_template}개보다 실제 가능한 고유 조합이 적어 "
                f"{available}개만 생성합니다. (템플릿/슬롯을 늘리면 더 많이 생성 가능)"
            )

        for inp_template, resp_template, slot_values in all_combos[:take]:
            fixed_slots = dict(zip(slot_names, slot_values))
            inp = inp_template
            resp = resp_template
            for name, value in fixed_slots.items():
                inp = inp.replace(f"{{{name}}}", value)
                resp = resp.replace(f"{{{name}}}", value)

            # 슬롯이 채워진 뒤에 조사를 해결해야 한다 — "{topic}은(는)"처럼 슬롯이
            # 아직 채워지지 않은 상태에서 처리하면 틀린 결과가 나온다 (korean_josa.py 참조).
            inp = resolve_dual_josa(inp)
            resp = resolve_dual_josa(resp)

            rows.append(
                {
                    "category": category,
                    "input": inp,
                    "response": resp,
                    "text": to_chatml(inp, resp, SYSTEM_PROMPT),
                }
            )

    # 멀티턴 대화 추가 (docs/15 7절 항목 4). 조합 생성이 아니라 직접 작성한
    # 대화 흐름을 그대로 사용한다 — 멀티턴은 순서/문맥이 중요해 슬롯 조합으로
    # 자동 생성하면 부자연스러워지기 쉽기 때문에 의도적으로 직접 작성했다.
    for turns in MULTI_TURN_CONVERSATIONS:
        rows.append(
            {
                "category": "multi_turn",
                "input": turns[0][0],
                "response": turns[-1][1],
                "text": to_chatml_multiturn(turns, SYSTEM_PROMPT),
                "turn_count": len(turns),
            }
        )

    rng.shuffle(rows)

    with open(out_path, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    unique_pairs = {(r["input"], r["response"]) for r in rows}
    print(f"\n생성 완료: {len(rows)}행 -> {out_path}")
    print(f"고유 (입력,응답) 조합: {len(unique_pairs)}개 (중복 없음, 전량 실제 서로 다른 조합)")
    print(f"카테고리 수: {len(CATEGORIES)}개 (단일 턴) + 멀티턴 대화 {len(MULTI_TURN_CONVERSATIONS)}개")

    from collections import Counter

    counter = Counter(r["category"] for r in rows)
    for cat, count in sorted(counter.items()):
        print(f"  {cat:>28}: {count}행")


